-- Central approval engine. One route definition for every later module.

CREATE TABLE workflows (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  company_id BIGINT UNSIGNED NOT NULL,
  code VARCHAR(40) NOT NULL,
  name VARCHAR(160) NOT NULL,
  description VARCHAR(500) NULL,
  transaction_kind ENUM('general', 'expenditure', 'organisational') NOT NULL,
  completion_role_code VARCHAR(60) NULL,
  status ENUM('active', 'inactive') NOT NULL DEFAULT 'active',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_workflows_code (company_id, code),
  KEY idx_workflows_status (company_id, status),
  CONSTRAINT fk_workflows_company FOREIGN KEY (company_id) REFERENCES companies (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE workflow_steps (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  workflow_id BIGINT UNSIGNED NOT NULL,
  step_order INT UNSIGNED NOT NULL,
  name VARCHAR(160) NOT NULL,
  resolver ENUM('role', 'supervisor', 'department_manager', 'position') NOT NULL,
  role_code VARCHAR(60) NULL,
  position_code VARCHAR(40) NULL,
  parallel_group INT UNSIGNED NULL,
  decision_kind ENUM('review', 'verify', 'approve') NOT NULL DEFAULT 'approve',
  requires_expenditure_authority TINYINT(1) NOT NULL DEFAULT 0,
  is_final_business_step TINYINT(1) NOT NULL DEFAULT 0,
  min_amount DECIMAL(18, 2) NULL,
  max_amount DECIMAL(18, 2) NULL,
  applies_to_department_id BIGINT UNSIGNED NULL,
  applies_to_branch_id BIGINT UNSIGNED NULL,
  status ENUM('active', 'inactive') NOT NULL DEFAULT 'active',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_workflow_steps_order (workflow_id, step_order),
  KEY idx_workflow_steps_workflow (workflow_id, status),
  CONSTRAINT fk_workflow_steps_workflow FOREIGN KEY (workflow_id) REFERENCES workflows (id),
  CONSTRAINT fk_workflow_steps_department FOREIGN KEY (applies_to_department_id) REFERENCES departments (id),
  CONSTRAINT fk_workflow_steps_branch FOREIGN KEY (applies_to_branch_id) REFERENCES branches (id),
  CONSTRAINT chk_workflow_step_amount CHECK (min_amount IS NULL OR max_amount IS NULL OR max_amount >= min_amount)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE approval_delegations (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  delegator_user_id BIGINT UNSIGNED NOT NULL,
  delegate_user_id BIGINT UNSIGNED NOT NULL,
  workflow_id BIGINT UNSIGNED NULL,
  starts_on DATE NOT NULL,
  ends_on DATE NOT NULL,
  reason VARCHAR(500) NOT NULL,
  status ENUM('active', 'revoked') NOT NULL DEFAULT 'active',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  revoked_at DATETIME(3) NULL,
  PRIMARY KEY (id),
  KEY idx_delegations_delegate (delegate_user_id, status, starts_on, ends_on),
  KEY idx_delegations_delegator (delegator_user_id, status),
  CONSTRAINT fk_delegations_delegator FOREIGN KEY (delegator_user_id) REFERENCES users (id),
  CONSTRAINT fk_delegations_delegate FOREIGN KEY (delegate_user_id) REFERENCES users (id),
  CONSTRAINT fk_delegations_workflow FOREIGN KEY (workflow_id) REFERENCES workflows (id),
  CONSTRAINT chk_delegations_not_self CHECK (delegator_user_id <> delegate_user_id),
  CONSTRAINT chk_delegations_dates CHECK (ends_on >= starts_on)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE approval_requests (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  company_id BIGINT UNSIGNED NOT NULL,
  reference_number VARCHAR(30) NOT NULL,
  workflow_id BIGINT UNSIGNED NOT NULL,
  title VARCHAR(180) NOT NULL,
  details VARCHAR(2000) NULL,
  amount DECIMAL(18, 2) NULL,
  currency_code CHAR(3) NOT NULL,
  department_id BIGINT UNSIGNED NULL,
  branch_id BIGINT UNSIGNED NULL,
  requester_user_id BIGINT UNSIGNED NOT NULL,
  status ENUM(
    'draft',
    'submitted',
    'pending_review',
    'under_approval',
    'approved',
    'rejected',
    'returned_for_correction',
    'processing',
    'completed',
    'cancelled'
  ) NOT NULL DEFAULT 'draft',
  revision INT UNSIGNED NOT NULL DEFAULT 0,
  submitted_at DATETIME(3) NULL,
  decided_at DATETIME(3) NULL,
  completed_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_approval_requests_reference (reference_number),
  KEY idx_approval_requests_status (status, updated_at),
  KEY idx_approval_requests_requester (requester_user_id, status),
  KEY idx_approval_requests_workflow (workflow_id),
  KEY idx_approval_requests_department (department_id),
  KEY idx_approval_requests_branch (branch_id),
  CONSTRAINT fk_approval_requests_company FOREIGN KEY (company_id) REFERENCES companies (id),
  CONSTRAINT fk_approval_requests_workflow FOREIGN KEY (workflow_id) REFERENCES workflows (id),
  CONSTRAINT fk_approval_requests_department FOREIGN KEY (department_id) REFERENCES departments (id),
  CONSTRAINT fk_approval_requests_branch FOREIGN KEY (branch_id) REFERENCES branches (id),
  CONSTRAINT fk_approval_requests_user FOREIGN KEY (requester_user_id) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE approval_request_steps (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  request_id BIGINT UNSIGNED NOT NULL,
  workflow_step_id BIGINT UNSIGNED NULL,
  step_order INT UNSIGNED NOT NULL,
  parallel_group INT UNSIGNED NULL,
  name VARCHAR(160) NOT NULL,
  resolver ENUM('role', 'supervisor', 'department_manager', 'position') NOT NULL,
  role_code VARCHAR(60) NULL,
  position_code VARCHAR(40) NULL,
  decision_kind ENUM('review', 'verify', 'approve') NOT NULL,
  requires_expenditure_authority TINYINT(1) NOT NULL DEFAULT 0,
  is_final_business_step TINYINT(1) NOT NULL DEFAULT 0,
  status ENUM('waiting', 'pending', 'approved', 'rejected', 'returned', 'skipped') NOT NULL DEFAULT 'waiting',
  decided_by_user_id BIGINT UNSIGNED NULL,
  delegation_id BIGINT UNSIGNED NULL,
  comment VARCHAR(1000) NULL,
  decided_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_request_steps_request (request_id, step_order),
  KEY idx_request_steps_status (status),
  CONSTRAINT fk_request_steps_request FOREIGN KEY (request_id) REFERENCES approval_requests (id),
  CONSTRAINT fk_request_steps_workflow_step FOREIGN KEY (workflow_step_id) REFERENCES workflow_steps (id) ON DELETE SET NULL,
  CONSTRAINT fk_request_steps_actor FOREIGN KEY (decided_by_user_id) REFERENCES users (id),
  CONSTRAINT fk_request_steps_delegation FOREIGN KEY (delegation_id) REFERENCES approval_delegations (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE approval_actions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  request_id BIGINT UNSIGNED NOT NULL,
  request_step_id BIGINT UNSIGNED NULL,
  actor_user_id BIGINT UNSIGNED NOT NULL,
  action ENUM('submit', 'approve', 'reject', 'return', 'resubmit', 'cancel', 'remind', 'process', 'complete') NOT NULL,
  comment VARCHAR(1000) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_approval_actions_request (request_id, created_at),
  CONSTRAINT fk_approval_actions_request FOREIGN KEY (request_id) REFERENCES approval_requests (id),
  CONSTRAINT fk_approval_actions_step FOREIGN KEY (request_step_id) REFERENCES approval_request_steps (id) ON DELETE SET NULL,
  CONSTRAINT fk_approval_actions_actor FOREIGN KEY (actor_user_id) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
